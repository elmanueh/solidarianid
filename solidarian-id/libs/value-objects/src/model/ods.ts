/**
 * Sustainable Development Goals (SDGs)
 *
 * Enum that represents the 17 United Nations Sustainable Development Goals.
 */
export enum SustainableDevelopmentGoal {
  /** Goal 1: End poverty in all its forms everywhere */
  NoPoverty = 1,

  /** Goal 2: End hunger, achieve food security and improved nutrition */
  ZeroHunger,

  /** Goal 3: Ensure healthy lives and promote well-being for all at all ages */
  GoodHealthAndWellBeing,

  /** Goal 4: Ensure inclusive and equitable quality education */
  QualityEducation,

  /** Goal 5: Achieve gender equality and empower all women and girls */
  GenderEquality,

  /** Goal 6: Ensure availability and sustainable management of water and sanitation */
  CleanWaterAndSanitation,

  /** Goal 7: Ensure access to affordable, reliable, sustainable and modern energy */
  AffordableAndCleanEnergy,

  /** Goal 8: Promote sustained, inclusive and sustainable economic growth */
  DecentWorkAndEconomicGrowth,

  /** Goal 9: Build resilient infrastructure, promote inclusive and sustainable industrialization */
  IndustryInnovationAndInfrastructure,

  /** Goal 10: Reduce inequality within and among countries */
  ReducedInequalities,

  /** Goal 11: Make cities and human settlements inclusive, safe, resilient and sustainable */
  SustainableCitiesAndCommunities,

  /** Goal 12: Ensure sustainable consumption and production patterns */
  ResponsibleConsumptionAndProduction,

  /** Goal 13: Take urgent action to combat climate change and its impacts */
  ClimateAction,

  /** Goal 14: Conserve and sustainably use the oceans, seas and marine resources */
  LifeBelowWater,

  /** Goal 15: Protect, restore and promote sustainable use of terrestrial ecosystems */
  LifeOnLand,

  /** Goal 16: Promote peaceful and inclusive societies, provide access to justice */
  PeaceJusticeAndStrongInstitutions,

  /** Goal 17: Strengthen the means of implementation and revitalize global partnerships */
  PartnershipsForTheGoals,
}
