import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString } from 'class-validator';

export class PushSubscriptionRequestDto {
  @ApiProperty({
    description: 'Push subscription endpoint generated by the browser',
    example: 'https://fcm.googleapis.com/fcm/send/abc123',
  })
  @IsString()
  @IsNotEmpty()
  endpoint: string;

  @ApiProperty({
    description: 'p256dh key from the browser push subscription',
    example: 'BOrQ8x1x3mM4x0K4k1M8JmK2dJ7t2l4J2n0mYzQdQ2w',
  })
  @IsString()
  @IsNotEmpty()
  p256dh: string;

  @ApiProperty({
    description: 'auth key from the browser push subscription',
    example: 'd3b8d5c1e4f2a7b9',
  })
  @IsString()
  @IsNotEmpty()
  auth: string;
}
